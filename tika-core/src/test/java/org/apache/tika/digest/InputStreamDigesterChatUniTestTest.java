package org.apache.tika.digest;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertThrows;

import java.nio.charset.StandardCharsets;

import org.junit.jupiter.api.Test;

import org.apache.tika.io.TikaInputStream;
import org.apache.tika.metadata.Metadata;
import org.apache.tika.parser.ParseContext;

/**
 * Tests generated by ChatUniTest and manually corrected so that they
 * compile and execute against the current Tika API.
 */
public class InputStreamDigesterChatUniTestTest {

    @Test
    public void testDigest() throws Exception {
        Encoder encoder = bytes -> "encoded";
        InputStreamDigester digester =
                new InputStreamDigester("SHA-256", "tk:digest:CHATUNITEST", encoder);

        Metadata metadata = new Metadata();

        try (TikaInputStream tis =
                     TikaInputStream.get("test".getBytes(StandardCharsets.UTF_8))) {
            digester.digest(tis, metadata, new ParseContext());
        }

        assertEquals("encoded", metadata.get("tk:digest:CHATUNITEST"));
        assertEquals("4", metadata.get(Metadata.CONTENT_LENGTH));
    }

    @Test
    public void testDigestWithOverriddenLength() throws Exception {
        Encoder encoder = bytes -> "encoded";
        InputStreamDigester digester =
                new InputStreamDigester("SHA-256", "tk:digest:CHATUNITEST", encoder);

        Metadata metadata = new Metadata();
        metadata.set(Metadata.CONTENT_LENGTH, "3");

        try (TikaInputStream tis =
                     TikaInputStream.get("test".getBytes(StandardCharsets.UTF_8))) {
            digester.digest(tis, metadata, new ParseContext());
        }

        assertEquals("encoded", metadata.get("tk:digest:CHATUNITEST"));

        // Existing content length must not be overwritten
        assertEquals("3", metadata.get(Metadata.CONTENT_LENGTH));
    }

    @Test
    public void testDigestWithoutEncoder() throws Exception {
        InputStreamDigester digester =
                new InputStreamDigester("SHA-256", "tk:digest:CHATUNITEST", null);

        Metadata metadata = new Metadata();

        try (TikaInputStream tis =
                     TikaInputStream.get("test".getBytes(StandardCharsets.UTF_8))) {

            assertThrows(
                    NullPointerException.class,
                    () -> digester.digest(tis, metadata, new ParseContext()));
        }
    }

    @Test
    public void testDigestWithInvalidAlgorithm() throws Exception {
        Encoder encoder = bytes -> "encoded";
        InputStreamDigester digester =
                new InputStreamDigester(
                        "THIS_ALGORITHM_DOES_NOT_EXIST",
                        "tk:digest:CHATUNITEST",
                        encoder);

        Metadata metadata = new Metadata();

        try (TikaInputStream tis =
                     TikaInputStream.get("test".getBytes(StandardCharsets.UTF_8))) {

            assertThrows(
                    IllegalArgumentException.class,
                    () -> digester.digest(tis, metadata, new ParseContext()));
        }
    }
}
